package.path="./lua/?.lua;"..package.path
local O=require("pass_input_observer")
local o=O.new({max_follow=5})
local function state(x,carrier)
 return {ball={x=x,y=10},possession="my",carrier_id=carrier}
end
local a=o.update(10,state(0,1),{Right=true},"test")
assert(a.input_status=="OBSERVED" and a.input_direction=="Right")
local b=o.update(11,state(0,1),{Right=true,B=true},"test")
assert(b.pass_event=="B_EDGE" and b.pass_kind=="HELD_SEQUENTIAL")
assert(b.pass_lead_frames==1 and b.pass_direction=="Right" and b.pass_id==1)
local c=o.update(12,state(15,1),{Right=true,B=true},"test")
assert(c.pass_dx==15 and c.pass_event==nil)
local d=o.update(13,state(30,5),{Right=true},"test")
assert(d.pass_event=="TEAMMATE_POSSESSION" and d.pass_receiver==5)
assert(o.update(14,state(30,5),{}, "test").pass_id==nil)
local e=o.update(15,state(30,5),{Up=true,B=true},"test")
assert(e.pass_kind=="SIMULTANEOUS" and e.pass_lead_frames==0)
o.update(20,state(10,1),{Left=true},"test")
o.update(21,state(10,1),{},"test")
local released=o.update(22,state(10,1),{B=true},"test")
assert(released.pass_kind=="RELEASED_THEN_B")
assert(released.pass_lead_frames==nil)
local missing=o.update(30,state(0,1),nil)
assert(missing.input_status=="UNAVAILABLE")
local only=o.update(31,state(0,1),{B=true})
assert(only.pass_kind=="B_ONLY")
assert(o.update(32,state(1,1),{B=true}).pass_event==nil)
local p=O.new()
local pa=p.update(100,state(0,1),{["P1 Right"]=true,["P1 B"]=false,["P2 B"]=true})
assert(pa.input_status=="OBSERVED" and pa.input_direction=="Right" and pa.input_b==0)
assert(pa.pass_note:find("P1 Right",1,true))
local pb=p.update(101,state(0,1),{["P1 Right"]=true,["P1 B"]=true})
assert(pb.pass_event=="B_EDGE" and pb.pass_lead_frames==1 and pb.pass_direction=="Right")
local diagonal=O.new()
local pd=diagonal.update(1,state(0,1),{["P1 Up"]=true,["P1 Right"]=true,["P1 B"]=true})
assert(pd.input_direction=="Up+Right" and pd.pass_kind=="SIMULTANEOUS")
local unknown=O.new().update(1,state(0,1),{["P2 B"]=true,["Odd Button"]=true})
assert(unknown.input_status=="UNKNOWN_LAYOUT" and unknown.pass_event==nil)
assert(unknown.pass_note:find("Odd Button",1,true))
print("pass input observer tests passed")
