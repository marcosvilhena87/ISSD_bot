package.path="./lua/?.lua;"..package.path
local Stats=require("pass_event_statistics")
local path="test_pass_events_tmp.csv"
local w=assert(Stats.new(path))
assert(not w.record(1,{pass_event="B_EDGE",pass_id=1}))
assert(w.record(2,{pass_event="TEAMMATE_POSSESSION",pass_id=1,pass_dominant="Right",pass_receiver=4,pass_outcome="MATCH"}))
assert(w.record(3,{pass_event="TEAMMATE_POSSESSION",pass_id=2,pass_dominant="Right",pass_receiver=4,pass_outcome="MATCH"}))
assert(w.record(4,{pass_event="OBSERVATION_TIMEOUT",pass_id=3,pass_dominant="Down+Right",pass_outcome="UNCONFIRMED"}))
w.close()
local f=assert(io.open(path,"r"))
local header=f:read("*l")
local a,b,c=f:read("*l"),f:read("*l"),f:read("*l")
assert(f:read("*l")==nil)
f:close();os.remove(path)
assert(header:find("direction_total",1,true))
assert(a:find("Right,4",1,true) and a:match(",1,1$"))
assert(b:match(",2,2$"))
assert(c:find("UNCONFIRMED",1,true))
print("pass event statistics tests passed")
